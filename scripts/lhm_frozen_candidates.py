"""Hash-pinned single-person frozen retries; selection is not visual acceptance."""

import fcntl
import hashlib
import json
import os
import re
import tempfile
from contextlib import contextmanager
from pathlib import Path

from worker.stages import lhm_recovery as recovery

SCHEMA = "wander.lhm-frozen-candidate/1"
SELECTION = "lhm-frozen-selection.json"
PREPARED = ("source.png", "mask.png", "prepared.json")


def _slug(slug):
    if not isinstance(slug, str) or not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]{0,63}", slug):
        raise ValueError("--lhm-frozen-candidate requires a safe 1–64 character slug")


def validate_options(args):
    slug = getattr(args, "lhm_frozen_candidate", None)
    if slug is None:
        return
    _slug(slug)
    if (
        getattr(args, "orchestrated", False)
        or getattr(args, "people", 0)
        or getattr(args, "all_people", False)
        or getattr(args, "only", None) != "lhm_frozen"
    ):
        raise ValueError("--lhm-frozen-candidate requires direct single-person --only lhm_frozen")


def _ctx(ctx):
    ctx = Path(ctx)
    if ctx.is_symlink() or not ctx.is_dir():
        raise ValueError("Frozen candidate run must be a regular directory")
    return ctx.resolve()


def _path(ctx, relative):
    path = ctx
    for part in Path(relative).parts:
        if part in {"..", "."}:
            raise ValueError("Unsafe frozen candidate path")
        path /= part
        if path.is_symlink():
            raise ValueError("Frozen candidate paths must not contain symlinks")
    if not path.resolve().is_relative_to(ctx):
        raise ValueError("Frozen candidate escaped run")
    return path


def _json(path):
    import json

    if path.is_symlink() or not path.is_file():
        raise ValueError(f"Missing regular frozen candidate receipt: {path.name}")
    try:
        value = json.loads(path.read_text())
    except (OSError, ValueError) as error:
        raise ValueError(f"Malformed frozen candidate receipt: {path.name}") from error
    if not isinstance(value, dict):
        raise ValueError("Frozen candidate receipt must be an object")
    return value


def _pin(path):
    if path.is_symlink() or not path.is_file():
        raise ValueError(f"Missing regular frozen candidate file: {path}")
    return {"bytes": path.stat().st_size, "sha256": recovery.file_hash(path)}


@contextmanager
def selection_lock(ctx):
    ctx = _ctx(ctx)
    path = _path(ctx, "lhm-frozen-selection.lock")
    descriptor = os.open(path, os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
    with os.fdopen(descriptor, "a") as stream:
        try:
            fcntl.flock(stream, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            raise ValueError("Frozen selection is busy") from None
        yield


def _inputs(ctx, clip, slug):
    prepared = _path(ctx, "prepared-person")
    files = {name: _pin(_path(prepared, name)) for name in PREPARED}
    if any(pin["bytes"] == 0 for pin in files.values()):
        raise ValueError("Prepared-person inputs must be nonempty")
    source = _pin(Path(clip))["sha256"]
    if _json(prepared / "prepared.json").get("sourceSha256") != source:
        raise ValueError("Prepared-person source hash differs from original clip")
    return {"schema": SCHEMA, "candidate": slug, "sourceSha256": source, "prepared": files}


def _directory(ctx, slug):
    _slug(slug)
    return _path(ctx, f"lhm-frozen-candidates/{slug}")


def _receipt_identity(receipt):
    # Recovery refreshes this bookkeeping field even when every generated byte is
    # unchanged. Everything else, including unknown future identity fields, is pinned.
    immutable = {key: value for key, value in receipt.items() if key != "recoveredAtEpoch"}
    raw = json.dumps(immutable, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()
    return {"identitySha256": hashlib.sha256(raw).hexdigest()}


def _legacy_receipt_identity(directory, pin):
    """Retain the original raw pin without rewriting a legacy success receipt.

    A snapshot can only be established while its bytes still match the selected
    historical hash. An already-changed legacy receipt cannot be inferred safely.
    """
    snapshot = _path(directory, "selected-recovery-receipt.json")
    if not snapshot.exists():
        receipt_path = _path(directory, "output/recovery-receipt.json")
        raw = receipt_path.read_bytes()
        if {"bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest()} != pin:
            raise ValueError(
                "Legacy frozen recovery identity cannot be established from changed bytes"
            )
        descriptor, temporary = tempfile.mkstemp(prefix=".selected-recovery-", dir=directory)
        try:
            with os.fdopen(descriptor, "wb") as stream:
                stream.write(raw)
                stream.flush()
                os.fsync(stream.fileno())
            try:
                os.link(temporary, snapshot)
            except FileExistsError:
                pass
        finally:
            Path(temporary).unlink(missing_ok=True)
    if _pin(snapshot) != pin:
        raise ValueError("Legacy frozen recovery identity snapshot changed")
    return _receipt_identity(_json(snapshot))


def _outputs(directory, pins):
    output = _path(directory, "output")
    receipt_path = _path(output, "recovery-receipt.json")
    receipt = recovery.load_receipt(receipt_path)
    manifest_path = _path(output, "recovery-manifest.json")
    manifest = _json(manifest_path)
    recovery.validate_manifest(manifest, receipt)
    if (
        receipt.get("mode") != "frozen"
        or receipt.get("status") != "recovered"
        or receipt.get("resultStatus") != "complete"
        or receipt.get("destination") != str(output)
        or receipt.get("recoveredDestination") != str(output)
        or receipt.get("manifestSha256") != recovery.file_hash(manifest_path)
        or manifest.get("status") != "complete"
    ):
        raise ValueError("Frozen output lacks complete recovered receipt/manifest")
    for name, item in manifest["files"].items():
        target = recovery.local_target(output, name)
        if _pin(target) != item:
            raise ValueError(f"Frozen output size/hash mismatch: {name}")
    problems = recovery.output_problems(
        output, "frozen", manifest["files"], manifest["requireRegistration"]
    )
    if problems:
        raise ValueError("Incomplete frozen output: " + "; ".join(problems))
    result = _json(output / "result.json")
    if result.get("sourceImageSha256") != pins["prepared"]["source.png"]["sha256"] or result.get(
        "prepared"
    ) != _json(directory.parent.parent / "prepared-person/prepared.json"):
        raise ValueError("Frozen result does not match pinned prepared inputs")
    # Include ancillary CLI artifacts and receipts as well as manifest-listed files.
    files = {}
    for path in sorted(output.rglob("*")):
        if path.is_symlink():
            raise ValueError("Frozen output contains a symlink")
        if path.is_file():
            name = path.relative_to(output).as_posix()
            if name == "recovery-receipt.json.lock":
                continue  # Empty lock bookkeeping is not a generated artifact.
            files[name] = (
                _receipt_identity(receipt) if name == "recovery-receipt.json" else _pin(path)
            )
    return files


def _read_selection(ctx, clip):
    path = _path(ctx, SELECTION)
    parent = _path(ctx, "lhm-frozen-candidates")
    if not path.exists():
        if any(parent.glob("*/selection.json")):
            raise ValueError("Frozen selection missing despite retained successful history")
        return None
    doc = _json(path)
    directory = _directory(ctx, doc.get("candidate"))
    pins = _inputs(ctx, clip, doc["candidate"])
    if _json(directory / "input-receipt.json") != pins:
        raise ValueError("Frozen candidate inputs changed")
    history = _json(directory / "selection.json")
    if history != doc:
        raise ValueError("Frozen selection or retained history changed")
    files = _outputs(directory, pins)
    selected_files = dict(doc.get("files", {}))
    selected_files.pop("recovery-receipt.json.lock", None)
    old_receipt_pin = selected_files.get("recovery-receipt.json")
    if isinstance(old_receipt_pin, dict) and set(old_receipt_pin) == {"bytes", "sha256"}:
        if _legacy_receipt_identity(directory, old_receipt_pin) != files["recovery-receipt.json"]:
            raise ValueError("Frozen recovery receipt identity changed")
        files["recovery-receipt.json"] = old_receipt_pin
    comparable = {**doc, "files": selected_files}
    expected = {
        "schema": SCHEMA,
        "candidate": doc["candidate"],
        "output": (directory / "output").relative_to(ctx).as_posix(),
        "inputs": pins,
        "inputReceipt": _pin(directory / "input-receipt.json"),
        "files": files,
    }
    if comparable != expected:
        raise ValueError("Frozen selection or retained output pins changed")
    return directory / "output"


def selected_directory(ctx, clip):
    ctx = _ctx(ctx)
    return _read_selection(ctx, clip) or ctx / "lhm-frozen"


def _guard_change(p):
    motion = Path(p.ctx) / "lhm-motion"
    stages = dict(p.state.data.get("stages", {}))
    state_path = getattr(p.state, "path", None)
    if state_path is not None and Path(state_path).exists():
        for name, row in _json(Path(state_path)).get("stages", {}).items():
            if isinstance(row, dict) and row.get("status") in {"running", "ok"}:
                stages[name] = row
    if (
        motion.exists()
        or motion.is_symlink()
        or any(
            (name.startswith("lhm_motion") or name.startswith("package"))
            and isinstance(row, dict)
            and row.get("status") in {"running", "ok"}
            for name, row in stages.items()
        )
    ):
        raise ValueError(
            "Frozen selection cannot change after retained/running motion or packaging"
        )


def validate_change(p):
    validate_options(p.a)
    slug = getattr(p.a, "lhm_frozen_candidate", None)
    if slug is None:
        return
    if p.state.done("lhm_frozen") and "lhm_frozen" not in (p.a.force or "").split(","):
        raise ValueError("--lhm-frozen-candidate requires --force lhm_frozen when cached")
    ctx = _ctx(p.ctx)
    with selection_lock(ctx):
        selected = _read_selection(ctx, p.clip)
        if selected != _directory(ctx, slug) / "output":
            _guard_change(p)


def run_candidate(p):
    """Called at start of single-person lhm_frozen; paid_run retains ledger authority."""
    slug = getattr(p.a, "lhm_frozen_candidate", None)
    ctx = _ctx(p.ctx)
    if (
        slug is None
        and not (ctx / SELECTION).exists()
        and not (ctx / SELECTION).is_symlink()
        and not (ctx / "lhm-frozen-candidates").exists()
        and not (ctx / "lhm-frozen-candidates").is_symlink()
    ):
        return False
    validate_options(p.a)
    with selection_lock(ctx):
        selected = _read_selection(ctx, p.clip)
        if slug is None:
            return selected is not None
        directory = _directory(ctx, slug)
        output = directory / "output"
        if selected == output:
            return True
        _guard_change(p)
        pins = _inputs(ctx, p.clip, slug)
        log = directory / "lhm_frozen.log"
        if directory.exists():
            if _json(directory / "input-receipt.json") != pins:
                raise ValueError("Frozen candidate inputs changed")
            if not output.exists():
                raise ValueError(
                    "Existing frozen candidate cannot resubmit; preserve it and use recovery"
                )
            if not p.recover_lhm(output, "frozen", log):
                raise ValueError("Retained frozen candidate requires recovery, never resubmission")
        else:
            directory.mkdir(parents=True, exist_ok=False)
            recovery.atomic_json(directory / "input-receipt.json", pins)
            recovery.atomic_json(directory / "submission-started.json", {"schema": SCHEMA})
            # This is the same logical operation/ledger and operator authorization as legacy.
            from run_clip import MODAL

            p.paid_run(
                "lhm_frozen",
                [
                    MODAL,
                    "run",
                    "worker/modal_lhm.py",
                    "--prepared",
                    str(ctx / "prepared-person"),
                    "--out",
                    str(output),
                ],
                log,
            )
        if _inputs(ctx, p.clip, slug) != pins:
            raise ValueError("Frozen inputs changed during candidate execution")
        files = _outputs(directory, pins)
        _guard_change(p)
        document = {
            "schema": SCHEMA,
            "candidate": slug,
            "output": output.relative_to(ctx).as_posix(),
            "inputs": pins,
            "inputReceipt": _pin(directory / "input-receipt.json"),
            "files": files,
        }
        history = _path(directory, "selection.json")
        if history.exists():
            raise ValueError(
                "Frozen candidate already retains successful history; selection not replaced"
            )
        recovery.atomic_json(history, document)
        recovery.atomic_json(_path(ctx, SELECTION), document)
        return True
